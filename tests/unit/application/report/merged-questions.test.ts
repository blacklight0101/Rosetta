import { describe, expect, it } from 'vitest';
import { buildReportModel } from '../../../../src/application/report/build-report-model.js';
import { buildReplay } from '../../../../src/application/report/replay-timeline.js';
import type { RunEvent } from '../../../../src/domain/runs/run-event.js';
import { renderReportMarkdown } from '../../../../src/infrastructure/report/report-markdown.js';
import { renderQuestionsHtml } from '../../../../src/infrastructure/report/site/questions-page.js';
import { auditHtml } from '../../../support/html-audit.js';
import { reportModel } from '../../../support/report-fixtures.js';

// RF-243, RF-646, RF-506, EV-57, P8-05: the report lists each pair of questions that was merged.

const runId = '20261012-100000-deepen';
const pair = {
  keptCardId: 'OQ-001',
  keptQuestion: 'Where are the invoice numbers generated?',
  keptRunKey: '20261010-090000-understand',
  mergedCardId: 'OQ-007',
  mergedQuestion: 'Where are the invoice numbers generated by the nightly job?',
  mergedRunKey: runId,
};
const at = '2026-10-12T10:00:01.000Z';
const events: RunEvent[] = [
  { schemaVersion: 1, seq: 1, at, runId, type: 'question.merged', data: pair },
  { schemaVersion: 1, seq: 2, at, runId, type: 'question.merged', data: { keptCardId: 4 } },
];
const masker = { mask: (value: string) => ({ text: value, hits: 0 }) } as never;

describe('P8-05 merged questions in the report', () => {
  it('builds the list from the events and leaves out data that does not fit', () => {
    const base = reportModel();
    const model = buildReportModel({
      ...{ run: { runKey: runId, stage: 'understand', endState: 'Completed' } as never },
      ...{ manifest: undefined, events, cardIndex: undefined, documents: base.documents },
      ...{ areas: [], generatedAt: base.generatedAt, coverage: null, cost: null },
      ...{ projectTotals: null, questions: [], cardDetails: [] },
    });
    expect(model.mergedQuestions).toEqual([pair]);
  });
  it('shows a replay step per merged pair', () => {
    expect(buildReplay(runId, events).steps).toMatchObject([
      { kind: 'question', label: 'Question merged' },
    ]);
  });
  it('lists the pairs in report.md with the kept question, the merged one and its run', () => {
    const text = renderReportMarkdown(reportModel({ mergedQuestions: [pair] }), masker);
    expect(text).toContain('## Merged questions');
    expect(text).toContain(pair.keptQuestion);
    expect(text).toContain(pair.mergedQuestion);
    expect(text).toContain(pair.mergedRunKey);
  });
  it('lists the pairs on the questions page', () => {
    const page = auditHtml(renderQuestionsHtml(reportModel({ mergedQuestions: [pair] })));
    const items = [...page.document.querySelectorAll('#merged-questions > li')];
    expect(items).toHaveLength(1);
    expect(items[0]?.textContent).toContain(pair.mergedQuestion);
  });
});
