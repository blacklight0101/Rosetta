import { describe, expect, it } from 'vitest';
import {
  mergedQuestionsOf,
  openQuestionsOf,
  sameQuestion,
} from '../../../../src/application/understand/open-questions.js';
import { assignCardIds } from '../../../../src/domain/cards/card-ids.js';
import { sameSubject } from '../../../../src/application/understand/same-question.js';
import { draftOf } from '../../../support/card-fixtures.js';
import { distinctPairs, nearRepeatPairs } from '../../../support/eshop-near-repeats.js';

// RF-646, RF-243, Q-52, EV-57, P8-05: the two repeats of the evaluation (synthetic names, the shapes
// of the real pairs: an opener in front of the same question, and a plural) merge; the distinct but
// similar pairs stay apart.

const ollamaAnswered = 'Where are the invoice numbers generated in the billing module?';
const ollamaAgain =
  'In the billing module, where are the invoice numbers generated by the nightly job?';
const haikuAnswered = 'Which roles can approve refunds?';
const haikuAgain = 'Which roles may approve the refund requests?';

describe('RF-646 EV-57 P8-05 sameQuestion on the pairs of the evaluation', () => {
  it('merges the Ollama shape: an opener before the same question word', () => {
    expect(sameQuestion(ollamaAnswered, ollamaAgain)).toBe(true);
  });
  it('merges the Haiku shape: a plural against a singular', () => {
    expect(sameQuestion(haikuAnswered, haikuAgain)).toBe(true);
  });
  it.each([
    [
      'Which roles can approve refunds over the daily limit?',
      'Which roles can approve exchanges over the daily limit?',
    ],
    [
      'In the billing module, where are invoice numbers generated?',
      'In the shipping module, where are invoice numbers generated?',
    ],
    ['How is the nightly export job scheduled?', 'How is the nightly import job scheduled?'],
  ])('keeps a distinct but similar pair apart: %s', (first, second) => {
    expect(sameQuestion(first, second)).toBe(false);
  });
});

function oq(title: string) {
  return draftOf({
    type: 'OQ',
    title,
    question: title,
    whyItMatters: 'It decides the specification.',
    claims: [
      { text: `Code behind ${title}`, citations: [{ path: 'a.cs', startLine: 1, endLine: 2 }] },
    ],
  });
}

function cardsOf(...questions: string[]) {
  const built = assignCardIds([
    { agentTaskId: 't1', area: 'billing', drafts: questions.map((each) => oq(each)) },
  ]);
  if (!built.ok) throw new Error('the test cards are invalid');
  return built.value;
}

describe('RF-243 EV-57 P8-05 one run asks a near-repeat once, by the shared rule', () => {
  it('groups the two Ollama-shaped questions of a run into one', () => {
    const cards = cardsOf(ollamaAnswered, ollamaAgain, 'Who owns the nightly export job?');
    expect(openQuestionsOf(cards, 'r1').map((each) => each.cardId)).toEqual(['OQ-001', 'OQ-003']);
  });
  it('keeps a distinct but similar pair as two questions', () => {
    const cards = cardsOf(
      'How is the nightly export job scheduled?',
      'How is the nightly import job scheduled?',
    );
    expect(openQuestionsOf(cards, 'r1')).toHaveLength(2);
  });
  it('lists each merged pair with the kept question first', () => {
    const cards = cardsOf(ollamaAnswered, ollamaAgain);
    expect(mergedQuestionsOf(cards, 'r1')).toEqual([
      {
        ...{ keptCardId: 'OQ-001', keptQuestion: ollamaAnswered, keptRunKey: 'r1' },
        ...{ mergedCardId: 'OQ-002', mergedQuestion: ollamaAgain, mergedRunKey: 'r1' },
      },
    ]);
  });
});

describe('RF-646 P9-13 near-repeat pairs of the eShop evaluation (threshold 75%)', () => {
  it.each(nearRepeatPairs)('merges %s / %s', (first, second) => {
    expect(sameQuestion(first, second) || sameSubject(first, second)).toBe(true);
  });
  it.each(distinctPairs)('keeps %s / %s apart', (first, second) => {
    expect(sameQuestion(first, second)).toBe(false);
  });
  it('leaves no pair of the recorded questions in the open list', () => {
    const cards = cardsOf(...nearRepeatPairs.flat());
    expect(openQuestionsOf(cards, 'r1')).toHaveLength(nearRepeatPairs.length);
  });
});
