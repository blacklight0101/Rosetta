import { describe, expect, it } from 'vitest';
import { dangerousIn } from '../../../support/render-markdown.js';
import { noUx } from '../../../../src/domain/planning/target-ux.js';
import { SecretMasker } from '../../../../src/infrastructure/guards/secret-masker.js';
import { renderHandoff } from '../../../../src/infrastructure/handoff/file-handoff-writer.js';
import { builtByPeople, handoffOf } from '../../../support/handoff-package-fixture.js';
import { htmlProblems } from '../../../support/html-check.js';
import { fakeOpenAiKey } from '../../../support/secret-fixture.js';
import { uxOf } from '../../../support/ux-fixtures.js';

// RF-626, RF-620, RF-602, RF-507: ux/ of the package: an index with the target screen map and
// every legacy screen kept, merged or dropped with its reason, one plain HTML wireframe per main
// screen, and the design brief for an external design tool.

const masker = new SecretMasker();

function filesOf(text = 'Plain text.', ux = uxOf(text)) {
  return renderHandoff({ ...handoffOf(text), ux }, masker);
}

describe('ux/README.md', () => {
  it('RF-626 draws the target screen map as one Mermaid diagram generated by code', () => {
    const index = filesOf()['ux/README.md'] ?? '';

    expect(index).toContain('# User-interface material');
    expect(index).toContain('## Target screen map');
    const diagram = index.split('```mermaid\n')[1]?.split('```')[0] ?? '';
    expect(diagram.split('\n')[0]).toBe('flowchart LR');
    expect(index.match(/^```.*$/gmu)).toEqual(['```mermaid', '```']);
  });

  it('RF-626 lists every legacy screen card as kept, merged or dropped, with its reason and its target', () => {
    const index = filesOf()['ux/README.md'] ?? '';

    expect(index).toContain(
      '| [SCRN-001](../sources.md#scrn-001) | Plain text. | merged | [Plain text.](wireframes/SCRN-001.html) | Plain text. |',
    );
    expect(index).toContain(
      '| [SCRN-003](../sources.md#scrn-003) | Plain text. | kept | [Plain text.](wireframes/SCRN-003.html) | Plain text. |',
    );
    expect(index).toContain(
      '| [SCRN-004](../sources.md#scrn-004) | Plain text. | dropped | none | Plain text. |',
    );
    const listed = [...index.matchAll(/^\| \[(SCRN-\d+)\]/gmu)].map((match) => match[1]);
    expect(listed).toEqual(['SCRN-001', 'SCRN-002', 'SCRN-003', 'SCRN-004']);
  });

  it('RF-626 lists the wireframes with the legacy screens each replaces', () => {
    const index = filesOf()['ux/README.md'] ?? '';

    expect(index).toContain(
      '- [wireframes/SCRN-001.html](wireframes/SCRN-001.html): Plain text. (replaces [SCRN-001](../sources.md#scrn-001), [SCRN-002](../sources.md#scrn-002))',
    );
  });

  it('RF-626 says the package holds no visual design and where the design brief is', () => {
    const index = filesOf()['ux/README.md'] ?? '';

    expect(index).toMatch(/no visual design/u);
    expect(index).toContain('[design brief](design-brief.md)');
  });

  it('RF-626 says so when no verified screen card exists, and writes no wireframe or brief', () => {
    const files = filesOf('Plain text.', noUx);

    expect(files['ux/README.md']).toContain('No verified screen card');
    expect(Object.keys(files).filter((name) => name.startsWith('ux/'))).toEqual(['ux/README.md']);
  });
});

describe('ux/wireframes/', () => {
  it('RF-626 one plain HTML file per main screen, none for a dropped legacy screen', () => {
    const names = Object.keys(filesOf()).filter((name) => name.startsWith('ux/wireframes/'));

    expect(names.sort()).toEqual(['ux/wireframes/SCRN-001.html', 'ux/wireframes/SCRN-003.html']);
  });

  it('RF-626 each wireframe passes the HTML check', () => {
    const files = filesOf('Plain text. <script>alert(1)</script> onerror=x');

    const pages = Object.entries(files).filter(([name]) => name.endsWith('.html'));
    expect(pages).toHaveLength(2);
    expect(pages.flatMap(([, text]) => htmlProblems(text))).toEqual([]);
    expect(files['ux/wireframes/SCRN-001.html']).toContain('&lt;script&gt;');
  });
});

describe('ux/design-brief.md', () => {
  it('RF-626 states the audience, the tone, the components needed and the accessibility target WCAG 2.1 AA', () => {
    const brief = filesOf()['ux/design-brief.md'] ?? '';

    expect(brief).toContain('# Design brief for an external design tool');
    expect(brief).toMatch(/## Audience\n\nPlain text\./u);
    expect(brief).toMatch(/## Tone\n\nPlain text\./u);
    expect(brief).toMatch(/## Components needed\n\n- Plain text\.\n- Data table/u);
    expect(brief).toMatch(/## Accessibility target\n\n[^\n]*WCAG 2\.1 AA/u);
  });

  it('RF-626 lists the screens to design, each linking its wireframe and the legacy screens it replaces', () => {
    const brief = filesOf()['ux/design-brief.md'] ?? '';

    expect(brief).toContain(
      '- [Plain text.](wireframes/SCRN-003.html): Plain text. Replaces [SCRN-003](../sources.md#scrn-003).',
    );
  });

  it('RF-626 holds no generated visual design and says the design comes from the design tool', () => {
    const brief = filesOf()['ux/design-brief.md'] ?? '';

    expect(brief).toMatch(/no (generated )?visual design/u);
    expect(brief).not.toMatch(/#[0-9a-f]{6}\b|font-family/iu);
  });

  it('RF-626 marks a part the planner left empty as a placeholder', () => {
    const empty = { ...uxOf('x'), designBrief: { audience: '', tone: '', components: [] } };

    const brief = filesOf('x', empty)['ux/design-brief.md'] ?? '';

    expect(brief.match(/Not stated: the cards do not say this/gu)).toHaveLength(3);
  });

  it('RF-626 names the roles the legacy screens mention and the front end the owner chose', () => {
    const brief = filesOf('Plain text.')['ux/design-brief.md'] ?? '';

    expect(brief).toContain('Roles named by the legacy screens: Plain text.');
    expect(brief).toContain('Front end: not chosen in the planning brief.');
  });
});

describe('ux/ and the package', () => {
  it('RF-620 the package README lists the user-interface material after the flows, linking the index', () => {
    const readme =
      renderHandoff(builtByPeople(handoffOf('Plain text.')), masker)['README.md'] ?? '';

    const order = readme
      .split('\n')
      .filter((line) => /^\d+\. \[/u.test(line))
      .slice(0, 5)
      .map((line) => line.replace(/^\d+\. /u, ''));
    expect(order).toEqual([
      '[Product requirements document](prd.md)',
      '[Technical requirements document](trd.md)',
      '[Target data model](data-model.md)',
      '[Target flows](flows/README.md)',
      '[User-interface material](ux/README.md)',
    ]);
  });

  it('RF-620 every link of the ux files resolves to a file of the package', () => {
    const files = filesOf();

    for (const name of Object.keys(files).filter(
      (each) => each.startsWith('ux/') && each.endsWith('.md'),
    )) {
      const links = [...(files[name] ?? '').matchAll(/\]\(([^)#]+)(?:#[^)]*)?\)/gu)].map(
        (m) => m[1] ?? '',
      );
      expect(links.length).toBeGreaterThan(0);
      const targets = links.map((link) => new URL(link, 'http://package/ux/').pathname.slice(1));
      expect(targets.filter((target) => !(target in files))).toEqual([]);
    }
  });
});

describe('ux/ model text', () => {
  const hostile = 'Plain <img src=x onerror=alert(1)> [x](javascript:alert(1)) ```';

  it('RF-507 adds no HTML, link or fence to a Markdown file', () => {
    const files = filesOf(hostile);

    const text = `${files['ux/README.md'] ?? ''}\n${files['ux/design-brief.md'] ?? ''}`;
    expect(dangerousIn(text)).toBeUndefined();
    expect(text.match(/\\<img/gu)?.length).toBeGreaterThan(4);
    expect(files['ux/README.md']?.match(/^```.*$/gmu)).toEqual(['```mermaid', '```']);
  });

  it('RNF-003 a secret in any text of the material is masked in every file', () => {
    const files = filesOf(`The key ${fakeOpenAiKey}`);

    const written = Object.entries(files).filter(([name]) => name.startsWith('ux/'));
    expect(written).toHaveLength(4);
    expect(written.map(([, text]) => text).join('\n')).not.toContain(fakeOpenAiKey.slice(8, 30));
  });
});
