import { describe, expect, it } from 'vitest';
import { SecretMasker } from '../../../../src/infrastructure/guards/secret-masker.js';
import { renderHandoff } from '../../../../src/infrastructure/handoff/file-handoff-writer.js';
import { handoffOf } from '../../../support/handoff-package-fixture.js';
import { fakeOpenAiKey } from '../../../support/secret-fixture.js';

// RF-625, RF-620, RF-602, ADR-013: flows/ of the package: an index of the main journeys and the
// journeys out of scope, and one file per main journey with its steps mapped to components and a
// Mermaid sequence diagram generated by code. Each file links the legacy FLOW card.

const masker = new SecretMasker();

function filesOf(text = 'Plain text.') {
  return renderHandoff(handoffOf(text), masker);
}

describe('flows/README.md', () => {
  it('RF-625 lists the main journeys with their files and legacy cards, and those out of scope with why', () => {
    const index = filesOf()['flows/README.md'] ?? '';

    expect(index).toContain('# Target flows');
    expect(index).toContain(
      '- [FLOW-001](FLOW-001.md): Plain text. (legacy flow card [FLOW-001](../sources.md#flow-001))',
    );
    expect(index).toContain('| [FLOW-002](../sources.md#flow-002) | Plain text. | Plain text. |');
  });

  it('RF-625 says so when no journey is mapped or out of scope', () => {
    const base = handoffOf('Plain text.');
    const files = renderHandoff({ ...base, flows: { flows: [], outOfScope: [] } }, masker);

    const index = files['flows/README.md'] ?? '';
    expect(index).toContain('No journey is mapped.');
    expect(index).toContain('No journey is out of scope.');
    expect(Object.keys(files).filter((name) => name.startsWith('flows/'))).toEqual([
      'flows/README.md',
    ]);
  });

  it('RF-620 the package README lists the flows after the data model, linking the index', () => {
    const readme = filesOf()['README.md'] ?? '';

    const order = readme
      .split('\n')
      .filter((line) => /^\d+\. \[/u.test(line))
      .slice(0, 4)
      .map((line) => line.replace(/^\d+\. /u, ''));
    expect(order).toEqual([
      '[Product requirements document](prd.md)',
      '[Technical requirements document](trd.md)',
      '[Target data model](data-model.md)',
      '[Target flows](flows/README.md)',
    ]);
  });
});

describe('flows/<FLOW-id>.md', () => {
  it('RF-625 one file per main journey, none for a journey out of scope', () => {
    const names = Object.keys(filesOf())
      .filter((name) => name.startsWith('flows/'))
      .sort();

    expect(names).toEqual(['flows/FLOW-001.md', 'flows/README.md']);
  });

  it('RF-625 links the legacy FLOW card, states trigger and outcome and maps each step to a component', () => {
    const file = filesOf()['flows/FLOW-001.md'] ?? '';

    expect(file).toContain('Legacy flow card: [FLOW-001](../sources.md#flow-001)');
    expect(file).toContain('Trigger: Plain text.');
    expect(file).toContain('Outcome: Plain text.');
    expect(file).toContain(
      '| 1 | FLOW\\-001.c1: Plain text. | [FEAT-001](../sources.md#feat-001) | Plain text. | Plain text. |',
    );
    expect(file).toContain('| 2 | FLOW\\-001.c2: Plain text. | none | not mapped |  |');
  });

  it('RF-625 holds a Mermaid sequence diagram generated by code, and no other code block', () => {
    const file = filesOf()['flows/FLOW-001.md'] ?? '';

    expect(file.match(/^```.*$/gmu)).toEqual(['```mermaid', '```']);
    const diagram = file.split('```mermaid\n')[1]?.split('```')[0] ?? '';
    expect(diagram.split('\n')[0]).toBe('sequenceDiagram');
    expect(diagram).toMatch(/^ {2}p1->>p2: 1\. /mu);
  });
});

describe('flows/<FLOW-id>.md: what the card leaves out', () => {
  it('RF-625 notes the steps of the legacy card the verifier did not support', () => {
    const base = handoffOf('Plain text.');
    const excluded = [{ claimId: 'FLOW-001.c3', cardId: 'FLOW-001', status: 'Rejected' as const }];
    const file = renderHandoff({ ...base, excluded }, masker)['flows/FLOW-001.md'] ?? '';

    expect(file).toContain('did not support and so left out: FLOW\\-001.c3.');
  });

  it('RF-625 says a trigger or outcome the card does not state is not stated', () => {
    const base = handoffOf('Plain text.');
    const [flow] = base.flows.flows;
    if (flow === undefined) throw new Error('The fixture has a flow');
    const flows = { ...base.flows, flows: [{ ...flow, trigger: '', outcome: '' }] };
    const file = renderHandoff({ ...base, flows }, masker)['flows/FLOW-001.md'] ?? '';

    expect(file).toContain('Trigger: not stated');
    expect(file).toContain('Outcome: not stated');
  });

  it('RNF-003 masks a secret in a flow file and its diagram', () => {
    const files = filesOf(`key ${fakeOpenAiKey}`);

    for (const name of ['flows/README.md', 'flows/FLOW-001.md']) {
      expect(files[name]).not.toContain(fakeOpenAiKey.slice(8, 30));
    }
  });
});
