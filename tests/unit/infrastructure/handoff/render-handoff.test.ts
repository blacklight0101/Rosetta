import { describe, expect, it } from 'vitest';
import type { HandoffPackage } from '../../../../src/application/plan/handoff-package.js';
import { assemblePlan } from '../../../../src/domain/planning/plan-content.js';
import type { PlanDraft } from '../../../../src/domain/planning/plan-draft.js';
import { buildBrief } from '../../../../src/domain/planning/planning-brief.js';
import { SecretMasker } from '../../../../src/infrastructure/guards/secret-masker.js';
import { renderHandoff } from '../../../../src/infrastructure/handoff/file-handoff-writer.js';
import { fakeOpenAiKey } from '../../../support/secret-fixture.js';
import { shippedCatalogue } from '../../../support/planning-brief-harness.js';

// RF-601, RF-602, RF-603, RNF-003, ADR-013: the files of the hand-off package as they are written.
// Model and repository text shows as text: it adds no HTML, link, heading, table cell or fence,
// and a secret in it is masked; the only diagram is generated by code.

const hostile = [
  '<img src=x onerror=alert(1)> [x](javascript:alert(1)) | cell',
  '# Title',
  '```js',
].join('\n');

function draft(text: string): PlanDraft {
  return {
    summary: text,
    requirements: [{ title: text, statement: text, sources: ['FEAT-001'] }],
    components: [
      { name: text, responsibility: text, dependsOn: ['Store'] },
      { name: 'Store', responsibility: 'Keeps data.', dependsOn: [] },
    ],
    decisions: [{ title: text, context: text, decision: text, consequences: text, sources: [] }],
    entities: [{ legacy: text, target: text, notes: text, sources: ['FEAT-001'] }],
    phases: [{ name: text, goal: text, exitCriteria: [text] }],
    tasks: [{ title: text, phase: 1, requirements: [1], acceptanceCriteria: [text] }],
    risks: [{ text, sources: ['FEAT-001'] }],
  };
}

function handoffOf(text: string): HandoffPackage {
  const brief = { ...buildBrief({}, shippedCatalogue), savedAt: '2026-10-12T09:30:00.000Z' };
  return {
    repository: { url: 'https://github.com/octo/demo', commitSha: 'c'.repeat(40) },
    sourceRun: '20261012-090000-understand',
    brief,
    style: { id: 'layered', title: 'Layered', rule: 'Layers call down.' },
    principles: [{ id: 'kiss', title: text, rule: text }],
    content: assemblePlan(draft(text), new Set(['FEAT-001'])).content,
    sources: [
      {
        ...{ id: 'FEAT-001', type: 'FEAT', title: text, summary: text, area: text },
        claims: [
          {
            claimId: 'FEAT-001.c1',
            text,
            citations: [{ path: 'src/a`b.cs', startLine: 1, endLine: 2 }],
            status: 'Supported',
          },
        ],
      },
    ],
    excluded: [{ claimId: 'FEAT-001.c2', cardId: 'FEAT-001', status: 'Rejected' }],
    briefQuestions: [{ id: 'migration', question: text, answer: text }],
    openQuestions: [{ cardId: 'OQ-001', question: text }],
  };
}

const masker = new SecretMasker();

/** The files whose text matches the pattern. */
function holding(files: Readonly<Record<string, string>>, pattern: RegExp): string[] {
  return Object.entries(files)
    .filter(([, text]) => pattern.test(text))
    .map(([path]) => path);
}

describe('renderHandoff', () => {
  it('RF-601 writes one decision record per decision, linked from the README', () => {
    const files = renderHandoff(handoffOf('Plain text.'), masker);

    expect(Object.keys(files)).toContain('decisions/ADR-001.md');
    expect(files['README.md']).toContain('](decisions/ADR-001.md)');
  });

  it('RF-603 model text adds no HTML, link, heading or fence to any file', () => {
    const files = renderHandoff(handoffOf(hostile), masker);

    expect(holding(files, /<[A-Za-z!/?]/u)).toEqual([]);
    expect(holding(files, /\]\(javascript/u)).toEqual([]);
    expect(holding(files, /^#+ Title/mu)).toEqual([]);
    expect(holding(files, /^```(?!(mermaid)?$)/mu)).toEqual([]);
  });

  it('RF-603 the component diagram codes the labels it draws', () => {
    const architecture = renderHandoff(handoffOf(hostile), masker)['architecture.md'] ?? '';
    const diagram = architecture.split('```mermaid\n')[1]?.split('```')[0] ?? '';

    expect(diagram.split('\n').filter((line) => line !== '')).toEqual([
      'flowchart LR',
      expect.stringMatching(/^ {2}c1\["[^"]*"\]$/u),
      '  c2["Store"]',
      '  c1 --> c2',
    ]);
  });

  it('RF-603 a table cell keeps its pipes as text', () => {
    const entities = renderHandoff(handoffOf(hostile), masker)['entity-mapping.md'] ?? '';
    const row = entities.split('\n').find((line) => line.includes('onerror')) ?? '';

    expect(row.replaceAll('\\|', '').split('|')).toHaveLength(6);
  });

  it('RNF-003 masks a secret in model text, the diagram labels included', () => {
    const files = renderHandoff(handoffOf(`key ${fakeOpenAiKey}`), masker);

    expect(holding(files, new RegExp(fakeOpenAiKey.slice(8, 30), 'u'))).toEqual([]);
  });
});
