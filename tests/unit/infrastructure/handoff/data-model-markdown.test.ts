import { describe, expect, it } from 'vitest';
import { dangerousIn } from '../../../support/render-markdown.js';
import {
  emptyDataModel,
  type ModelColumn,
  type TargetDataModel,
} from '../../../../src/domain/planning/data-model.js';
import { markdownEscaper } from '../../../../src/infrastructure/cards/markdown-text.js';
import { SecretMasker } from '../../../../src/infrastructure/guards/secret-masker.js';
import { dataModelMarkdown } from '../../../../src/infrastructure/handoff/handoff-data-model-markdown.js';
import { targetModel } from '../../../support/data-model-fixtures.js';
import { fakeOpenAiKey } from '../../../support/secret-fixture.js';

// RF-623, RF-603, RF-602, RNF-003, ADR-013: `data-model.md` of the hand-off package. Tables with
// columns, types, keys, constraints and indexes; the legacy source of each column or "new"; the
// dropped legacy fields with reasons; the type changes that can lose data as migration risks; a
// Mermaid diagram generated by code; no executable DDL, and model text only as escaped text.

const masker = new SecretMasker();

function render(model: TargetDataModel): string {
  return dataModelMarkdown(model, markdownEscaper(masker), masker);
}

/** The text as a reader sees it: the escaper's backslashes removed. */
function plain(text: string): string {
  return text.replaceAll('\\', '');
}

function hostileModel(text: string): TargetDataModel {
  const model = targetModel();
  const [first, ...rest] = model.tables;
  if (first === undefined) throw new Error('The fixture has tables');
  const columns: ModelColumn[] = first.columns.map((column) => ({
    ...column,
    migrationRisk: text,
    type: text,
    ...(column.legacy === null ? {} : { legacy: { ...column.legacy, field: text } }),
  }));
  return {
    ...model,
    database: text,
    tables: [
      {
        ...first,
        purpose: text,
        columns,
        checks: [text],
        indexes: [{ columns: ['id'], unique: false, reason: text }],
      },
      ...rest,
    ],
    dropped: model.dropped.map((field) => ({ ...field, field: text, reason: text })),
  };
}

describe('dataModelMarkdown: the tables', () => {
  it('RF-623 lists each table with its columns, types and nullability', () => {
    const text = plain(render(targetModel()));

    expect(text).toContain('### customer_order\n');
    expect(text).toContain('Keeps one order a customer placed.');
    expect(text).toContain('| Column | Type | Nullable | Legacy source |');
    expect(text).toContain('| customer_id | uuid | no | new |');
    expect(text).toContain('| total | numeric(10,2) | yes | new |');
  });

  it('RF-623 names the legacy card, claim and field of a column, or says new', () => {
    const text = plain(render(targetModel()));

    expect(text).toContain(
      '| status | varchar(20) | no | [ENT-001](sources.md#ent-001) ENT-001.c1: Status |',
    );
    expect(text).toContain('Built from: [ENT-002](sources.md#ent-002)');
  });

  it('RF-623 lists the keys, the constraints and the indexes of a table', () => {
    const text = plain(render(targetModel()));

    expect(text).toContain('- Primary key: id\n');
    expect(text).toContain('- Unique: email\n');
    expect(text).toContain('- Foreign key: customer_id references customer (id)\n');
    expect(text).toContain('- Check: total is zero or more\n');
    expect(text).toContain('- Index on customer_id: Orders are listed by customer.\n');
  });
});

describe('dataModelMarkdown: the header', () => {
  it('RF-623 states the database of the brief, or that none was chosen', () => {
    expect(plain(render(targetModel()))).toContain('Database: **PostgreSQL**');
    const none = plain(render({ ...targetModel(), database: null }));

    expect(none).toContain('not chosen');
    expect(none).toContain('to confirm');
  });

  it('RF-623 links the entity mapping, and the diagram is a Mermaid block made by code', () => {
    const text = render(targetModel());

    expect(text).toContain('](entity-mapping.md)');
    expect(text).toContain('```mermaid\nerDiagram\n  e1["customer"] {');
  });

  it('RF-623 a model without a table says so and draws no diagram', () => {
    const text = render(emptyDataModel('PostgreSQL'));

    expect(text).toContain('no legacy entity');
    expect(text).not.toContain('```');
  });
});

describe('dataModelMarkdown: dropped fields and migration risks', () => {
  it('RF-623 lists a dropped legacy field with its claim, card and reason', () => {
    const text = plain(render(targetModel()));

    expect(text).toContain('## Dropped legacy fields');
    expect(text).toContain(
      '| Fax | ENT-002.c2 | [ENT-002](sources.md#ent-002) | The new system contacts customers by email only. |',
    );
  });

  it('RF-623 marks a claim the planner left unmapped and unlisted as listed by the code', () => {
    const text = plain(render(targetModel()));

    expect(text).toMatch(
      /\| not named \| ENT-002\.c3 \| .* \| The planner wrote no target column/u,
    );
  });

  it('RF-623 lists a type change that can lose data as a migration risk with its column', () => {
    const risks = plain(render(targetModel())).split('## Migration risks\n')[1] ?? '';

    expect(risks).toContain(
      '- customer_order.status ([ENT-001](sources.md#ent-001) ENT-001.c1): The legacy status is free text; a value outside the new list is refused.',
    );
    expect(risks.match(/^- /gmu)).toHaveLength(1);
  });

  it('RF-623 a model with no risk says none was found', () => {
    const model = targetModel();
    const tables = model.tables.map((table) => ({
      ...table,
      columns: table.columns.map((column) => ({ ...column, migrationRisk: '' })),
    }));

    expect(plain(render({ ...model, tables }))).toContain('No type change that can lose data');
  });
});

describe('dataModelMarkdown: no executable DDL, only escaped text', () => {
  it('RF-603 holds no fence but the generated diagram and no statement', () => {
    const text = render(targetModel());

    expect(text.match(/^```.*$/gmu)).toEqual(['```mermaid', '```']);
    expect(text).not.toMatch(/\b(?:create|alter|drop)\s+(?:table|index|database)\b/iu);
    expect(text).not.toMatch(/;\s*$/mu);
  });

  it('RF-603 model text adds no HTML, link, heading or fence, and no table cell breaks', () => {
    const hostile = '<img src=x onerror=alert(1)> [x](javascript:alert(1)) | cell\n# Title\n```js';
    const text = render(hostileModel(hostile));

    expect(dangerousIn(text)).toBeUndefined();
    expect(text).not.toMatch(/^#+ Title/mu);
    expect(text.match(/^```.*$/gmu)).toEqual(['```mermaid', '```']);
    const row = text.split('\n').find((line) => line.startsWith('| email')) ?? '';
    expect(row.replaceAll('\\|', '').split('|')).toHaveLength(6);
  });

  it('RNF-003 masks a secret in model text, the diagram included', () => {
    const text = render(hostileModel(`key ${fakeOpenAiKey}`));

    expect(text).not.toContain(fakeOpenAiKey.slice(8, 30));
  });
});

describe('dataModelMarkdown: defaults', () => {
  it('P5-37 shows the default a legacy claim states next to the nullability', () => {
    const model = targetModel();
    const tables = model.tables.map((table) => ({
      ...table,
      columns: table.columns.map((each) =>
        each.name === 'customer_id' ? { ...each, default: '0' } : each,
      ),
    }));

    const text = plain(render({ ...model, tables }));

    expect(text).toContain('| customer_id | uuid | no, default 0 | new |');
  });
});

describe('dataModelMarkdown: a table copied from the legacy model (P5-38)', () => {
  it('RF-623 marks a table built from the legacy claims and no other', () => {
    const model = targetModel();
    const [first, ...rest] = model.tables;
    if (first === undefined) throw new Error('The fixture has tables');

    const text = plain(
      render({ ...model, tables: [{ ...first, copiedFromLegacy: true }, ...rest] }),
    );

    expect(text.match(/Copied from the legacy model/gu)).toHaveLength(1);
    expect(plain(render(model))).not.toContain('Copied from the legacy model');
  });
});
