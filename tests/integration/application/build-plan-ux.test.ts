import { readFile } from 'node:fs/promises';
import { describe, expect, it } from 'vitest';
import { htmlProblems } from '../../support/html-check.js';
import { planCards } from '../../support/plan-cards.js';
import { plain, seededUxPlan, uxFilesOf } from '../../support/ux-plan-harness.js';
import { useTempRoot } from '../../support/temp-root.js';

// RF-626, RF-620, Q-27, RF-507, ADR-008: the user-interface material of the hand-off package from
// a plan run over a seeded understand run with SCRN cards, real files in a temporary data folder
// and the real provider factory. The planner's sixth call replays the screens in
// tests/recordings/fake/planner-package.json.

const temp = useTempRoot('rosetta-ux-');

async function packageOf() {
  const h = await seededUxPlan(temp.path);
  const run = await h.plan();
  return { h, run, written: await h.handoffOf(run) };
}

describe('BuildPlan: what the screens call is sent', () => {
  it('RF-626 sends the verified SCRN cards with their screen detail and the owner front end, as data', async () => {
    const h = await seededUxPlan(temp.path);

    const run = await h.plan();

    expect(run.endState).toBe('Completed');
    const request = h.providers.requests()[5];
    const message = request?.messages.map((each) => each.content).join('\n') ?? '';
    for (const sent of [
      'SCRN-001',
      '"route": "/orders"',
      '"name": "Status"',
      '"flow": "FLOW-001"',
      '"handler": "openOrder"',
      'SCRN-005.c1',
      'src/Orders/Orders.cshtml:3-9',
      '"frontEnd": "React"',
    ]) {
      expect(message).toContain(sent);
    }
    for (const left of ['Place an order', 'FLOW-001.c1', 'ENT-001']) {
      expect(message).not.toContain(left);
    }
    expect(request?.system).toBe(await readFile('prompts/planner/ux.v1.md', 'utf8'));
    expect(request?.context).toMatchObject({ role: 'planner', agentTaskId: 'planner-ux' });
    const callIds = h.providers.requests().map((each) => each.context.callId);
    expect(new Set(callIds).size).toBe(6);
  });

  it('RF-626 without a verified SCRN card the screens are not asked for and the index says so', async () => {
    const h = await seededUxPlan(temp.path, { cards: [...planCards()] });

    const written = await h.handoffOf(await h.plan());

    expect(h.providers.requests().map((each) => each.context.agentTaskId)).not.toContain(
      'planner-ux',
    );
    expect(uxFilesOf(written)).toEqual(['ux/README.md']);
    expect(written['ux/README.md']).toContain('No verified screen card');
  });
});

describe('BuildPlan: ux/', () => {
  it('RF-626 writes the index, one wireframe per main screen and the design brief', async () => {
    const { written } = await packageOf();

    expect(uxFilesOf(written)).toEqual([
      'ux/README.md',
      'ux/design-brief.md',
      'ux/wireframes/SCRN-001.html',
      'ux/wireframes/SCRN-003.html',
    ]);
  });

  it('RF-626 every verified SCRN card is kept, merged or dropped with a reason, and linked to its card', async () => {
    const { written } = await packageOf();

    const index = plain(written['ux/README.md']);
    expect(index).toMatch(
      /\| \[SCRN-001\]\(\.\.\/sources\.md#scrn-001\) \| \/orders \| merged \|/u,
    );
    expect(index).toMatch(/\| \[SCRN-002\].*\| merged \|/u);
    expect(index).toMatch(
      /\| \[SCRN-003\].*\| kept \| \[Checkout.*\]\(wireframes\/SCRN-003\.html\) \|/u,
    );
    expect(index).toMatch(
      /\| \[SCRN-004\].*\| dropped \| none \| The fax page is not part of the new shop\. \|/u,
    );
    expect(index).toMatch(
      /\| \[SCRN-005\].*\| dropped \| none \|.*neither kept, merged nor dropped/u,
    );
    const listed = [...index.matchAll(/^\| \[(SCRN-\d+)\]/gmu)].map((match) => match[1]);
    expect(listed).toEqual(['SCRN-001', 'SCRN-002', 'SCRN-003', 'SCRN-004', 'SCRN-005']);
  });

  it('RF-626 the target screen map is a Mermaid diagram generated by code', async () => {
    const { written } = await packageOf();

    const index = written['ux/README.md'] ?? '';
    const diagram = index.split('```mermaid\n')[1]?.split('```')[0] ?? '';
    expect(diagram.split('\n')[0]).toBe('flowchart LR');
    expect(diagram).toMatch(/^ {2}l1 -->\|merged\| t1$/mu);
    expect(diagram).toMatch(/^ {2}t1 --> t2$/mu);
    expect(diagram).not.toMatch(/<|click |javascript/u);
    expect(index.match(/^```.*$/gmu)).toEqual(['```mermaid', '```']);
  });
});

describe('BuildPlan: ux/ wireframes', () => {
  it('RF-626 a wireframe lists its fields, actions and navigation from the legacy cards it replaces', async () => {
    const { written } = await packageOf();

    const html = written['ux/wireframes/SCRN-001.html'] ?? '';
    for (const shown of [
      'Search (text, optional)',
      'Status (dropdown, optional)',
      'Order number (text, required)',
      'Open order (handler openOrder)',
      'Place order (starts flow FLOW-001)',
      'Cancel order (handler cancelOrder)',
    ]) {
      expect(html).toContain(shown);
    }
    expect(html).toContain('href="SCRN-003.html"');
    expect(html).toContain('/ghost');
    expect(html).not.toContain('href="/ghost"');
  });

  it('RF-626 RF-507 every wireframe passes the HTML check and a hostile screen name renders as text', async () => {
    const { written } = await packageOf();

    const pages = uxFilesOf(written).filter((each) => each.endsWith('.html'));
    expect(pages).toHaveLength(2);
    expect(pages.flatMap((name) => htmlProblems(written[name] ?? ''))).toEqual([]);
    const checkout = written['ux/wireframes/SCRN-003.html'] ?? '';
    expect(checkout).toContain('Checkout &lt;/title&gt;&lt;script&gt;alert(1)&lt;/script&gt;');
    expect(checkout).not.toContain('<script');
    expect(checkout.match(/<title>/gu)).toHaveLength(1);
    const orders = written['ux/wireframes/SCRN-001.html'] ?? '';
    expect(orders).toContain('&lt;img src=x onerror=alert(1)&gt;');
    expect(orders).not.toContain('<img');
  });

  it('RF-626 the design brief holds the audience, tone, components and the WCAG 2.1 AA target', async () => {
    const { written } = await packageOf();

    const brief = plain(written['ux/design-brief.md']);
    expect(brief).toContain('Shoppers who order and staff who handle the orders.');
    expect(brief).toContain('Calm and plain.');
    expect(brief).toContain('- Confirmation dialog');
    expect(brief).toContain('WCAG 2.1 AA');
    expect(brief).toContain('Front end: React');
    expect(brief).toContain('Roles named by the legacy screens: Shopper, Staff.');
    expect(brief).not.toMatch(/<script|\]\(javascript/u);
  });
});

describe('BuildPlan: ux/ and the package', () => {
  it('RF-620 the package README lists the user-interface material after the flows and before the requirements', async () => {
    const { written } = await packageOf();

    const readme = written['README.md'] ?? '';
    expect(readme).toContain('](ux/README.md)');
    expect(readme.indexOf('](flows/README.md)')).toBeLessThan(readme.indexOf('](ux/README.md)'));
    expect(readme.indexOf('](ux/README.md)')).toBeLessThan(readme.indexOf('](requirements.md)'));
  });

  it('RF-626 the log names what the checks refused', async () => {
    const { h } = await packageOf();

    const warned = h.s.logger.entries
      .filter((entry) => entry.level === 'warn')
      .map((entry) => entry.message)
      .join(' ');
    expect(warned).toContain('2 screen(s) without a verified SCRN card');
    expect(warned).toContain('5 card id(s)');
  });
});
