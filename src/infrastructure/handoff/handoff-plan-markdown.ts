// RF-601, RF-602, RF-603, ADR-013: the planning documents of the hand-off package: requirements,
// target architecture, decision records and entity mapping (the roadmap and the task cards are in
// handoff-roadmap-markdown.ts and handoff-task-markdown.ts). Plain Markdown;
// the only diagram is a Mermaid block generated by code. Model text is escaped (and masked) by the
// escaper, so it shows as text and can add no link, heading, table or HTML.

// RF-601, RF-602
export function requirementsMarkdown(handoff: HandoffPackage, esc: MarkdownEscaper): string {
  return [
    '# Requirements specification',
    '',
    'What the new system must do. Every requirement names the cards it comes from; each card in',
    `[the source cards](${handoffFiles.sources}) lists the claims and their citations into the legacy code.`,
    '',
    ...handoff.content.requirements.flatMap((requirement) => [
      `## ${requirement.id}`,
      '',
      `**${esc.inline(requirement.title)}**`,
      '',
      esc.block(requirement.statement),
      '',
      `Source cards: ${sourceLinks(requirement.sources)}`,
      '',
    ]),
  ].join('\n');
}

/** RF-608: the sentence on the style; it no longer says the components follow it when a rule is broken. */
function followingSentence(handoff: HandoffPackage, esc: MarkdownEscaper): string {
  const { style, choices } = handoff;
  const linked = choices.style === '' ? '' : ` (${decisionLink(choices.style)})`;
  const title = esc.inline(style.title);
  const check = `How to check it: ${esc.inline(style.check)}`;
  const broken = `See [the package checks](${handoffFiles.checks}) and [the risks](${handoffFiles.risks}).`;
  if (hasOwnAnswer(handoff, 'architecture')) {
    // DEC-184: the style is not chosen; Rosetta's dependency check only compares with it.
    const compares = `Rosetta's automatic dependency check compares the components below with the ${title} style${linked}, ${referenceKind(handoff)} and ${checkReference('style')}, not the chosen style`;
    return followsStyle(handoff)
      ? `${compares}; they keep its rule. ${check}`
      : `${compares}, and at least one dependency breaks its rule. ${broken} ${check}`;
  }
  if (!followsStyle(handoff)) {
    return `The components below do not all follow the ${title} style${linked}: at least one dependency breaks its rule. ${broken} ${check}`;
  }
  return `The components below follow the ${title} style${linked}. ${check}`;
}

/** The style the file opens with: the owner's own answer first and the default as the reference. */
function styleOpening(handoff: HandoffPackage, esc: MarkdownEscaper): string[] {
  const { style, choices } = handoff;
  if (!hasOwnAnswer(handoff, 'architecture')) {
    return [`Architecture style: **${esc.inline(style.title)}**. ${esc.inline(style.rule)}`, ''];
  }
  const record = choices.style === '' ? '' : ` (${decisionLink(choices.style)})`;
  return [
    ...ownAnswerLines(handoff, 'architecture', esc),
    referenceLine(esc.inline(style.title), record, 'style', esc.inline(style.rule)),
    '',
  ];
}

// RF-601, RF-603
export function architectureMarkdown(
  handoff: HandoffPackage,
  esc: MarkdownEscaper,
  masker: TextMasker,
): string {
  const { content } = handoff;
  const masked = content.components.map((component) => ({
    name: masker.mask(component.name).text,
    dependsOn: component.dependsOn.map((name) => masker.mask(name).text),
  }));
  const diagram = content.components.length === 0 ? [] : fenced(componentDiagram(masked));
  return [
    '# Target architecture',
    '',
    ...styleOpening(handoff, esc),
    esc.block(content.summary === '' ? 'The planner wrote no summary.' : content.summary),
    '',
    '## Following the style',
    '',
    followingSentence(handoff, esc),
    '',
    '## Components',
    '',
    ...diagram,
    ...(content.components.length === 0
      ? ['The planner named no component.']
      : content.components.map(
          (component) =>
            `- **${esc.inline(component.name)}**${component.role === '' ? '' : ` (${esc.inline(component.role)})`}: ${esc.inline(component.responsibility)}`,
        )),
    '',
  ].join('\n');
}

/** The options considered, when the record lists any. */
function optionLines(decision: PlanDecision, esc: MarkdownEscaper): string[] {
  if (decision.options.length === 0) return [];
  return [
    '## Options considered',
    '',
    ...decision.options.map((option) => `- ${esc.inline(option)}`),
    '',
  ];
}

// RF-601, RF-608, RF-609, RF-610
export function decisionMarkdown(decision: PlanDecision, esc: MarkdownEscaper): string {
  return [
    `# ${decision.id} ${esc.inline(decision.title)}`,
    '',
    `Status: ${decision.status}`,
    '',
    '## Context',
    '',
    esc.block(decision.context),
    '',
    ...optionLines(decision, esc),
    '## Decision',
    '',
    esc.block(decision.decision),
    '',
    '## Consequences',
    '',
    esc.block(decision.consequences === '' ? 'Not stated.' : decision.consequences),
    '',
    `Source cards: ${sourceLinks(decision.sources, 1)}`,
    '',
  ].join('\n');
}

/** The notes of the planner, then its own name for the target when that is not one of the tables. */
function notesOf(entity: DraftEntity, tables: readonly string[], split: readonly string[]): string {
  const named = entity.target.trim();
  const same = tables.some((name) => name.toLowerCase() === named.toLowerCase());
  return [entity.notes, named === '' || same ? '' : `The planner named it ${named}.`, ...split]
    .filter((part) => part !== '')
    .join(' ');
}

const noTable = 'No table in the target data model';

// RF-601, RF-602, P5-33
export function entityMappingMarkdown(handoff: HandoffPackage, esc: MarkdownEscaper): string {
  const rows = handoff.content.entities.map((entity) => {
    const tables = tablesOfEntity(entity, handoff.dataModel);
    const target =
      tables.length === 0 ? noTable : tables.map((name) => esc.inline(name)).join(', ');
    return `| ${esc.inline(entity.legacy)} | ${target} | ${esc.inline(notesOf(entity, tables, splitNotesOf(entity, handoff.dataModel)))} | ${sourceLinks(entity.sources)} |`;
  });
  return [
    '# Entity mapping',
    '',
    'How each legacy entity maps to a table of the new system. The table names are those of the target data model.',
    '',
    `The tables, columns and keys of the target entities are in [the target data model](${handoffFiles.dataModel}).`,
    '',
    ...(rows.length === 0
      ? ['The planner mapped no entity.']
      : ['| Legacy entity | Target table | Notes | Source cards |', '|---|---|---|---|', ...rows]),
    '',
  ].join('\n');
}
