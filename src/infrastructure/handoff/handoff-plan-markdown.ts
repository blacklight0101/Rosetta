import type { HandoffPackage } from '../../application/plan/handoff-package.js';
import { componentDiagram } from '../../domain/diagrams/component-diagram.js';
import type { PlanDecision, PlanPhase } from '../../domain/planning/plan-content.js';
import { fenced } from '../cards/flow-diagram-section.js';
import type { MarkdownEscaper } from '../cards/markdown-text.js';
import type { TextMasker } from '../guards/secret-masker.js';
import { bullets, handoffFiles, idLink, sourceLinks } from './handoff-links.js';

// RF-601, RF-602, RF-603, ADR-013: the planning documents of the hand-off package: requirements,
// target architecture, decision records, entity mapping, roadmap and task cards. Plain Markdown;
// the only diagram is a Mermaid block generated by code. Model text is escaped (and masked) by the
// escaper, so it shows as text and can add no link, heading, table or HTML.

/** The phase's link in the roadmap (its heading is `## Phase <n>`), then its name as text. */
function phaseLink(phase: PlanPhase | undefined, number: number, esc: MarkdownEscaper): string {
  const name = phase === undefined ? '' : ` ${esc.inline(phase.name)}`;
  return `[Phase ${String(number)}](${handoffFiles.roadmap}#phase-${String(number)})${name}`;
}

// RF-601, RF-602
export function requirementsMarkdown(handoff: HandoffPackage, esc: MarkdownEscaper): string {
  return [
    '# Requirements specification',
    '',
    'What the new system must do. Every requirement names the cards it comes from; each card in',
    `[the source cards](${handoffFiles.sources}) lists the claims and their citations into the legacy code.`,
    '',
    ...handoff.content.requirements.flatMap((requirement) => [
      `## ${requirement.id}`,
      '',
      `**${esc.inline(requirement.title)}**`,
      '',
      esc.block(requirement.statement),
      '',
      `Source cards: ${sourceLinks(requirement.sources)}`,
      '',
    ]),
  ].join('\n');
}

// RF-601, RF-603
export function architectureMarkdown(
  handoff: HandoffPackage,
  esc: MarkdownEscaper,
  masker: TextMasker,
): string {
  const { content, style } = handoff;
  const masked = content.components.map((component) => ({
    name: masker.mask(component.name).text,
    dependsOn: component.dependsOn.map((name) => masker.mask(name).text),
  }));
  const diagram = content.components.length === 0 ? [] : fenced(componentDiagram(masked));
  return [
    '# Target architecture',
    '',
    `Architecture style: **${esc.inline(style.title)}**. ${esc.inline(style.rule)}`,
    '',
    esc.block(content.summary === '' ? 'The planner wrote no summary.' : content.summary),
    '',
    '## Components',
    '',
    ...diagram,
    ...(content.components.length === 0
      ? ['The planner named no component.']
      : content.components.map(
          (component) =>
            `- **${esc.inline(component.name)}**: ${esc.inline(component.responsibility)}`,
        )),
    '',
  ].join('\n');
}

// RF-601
export function decisionMarkdown(decision: PlanDecision, esc: MarkdownEscaper): string {
  return [
    `# ${decision.id} ${esc.inline(decision.title)}`,
    '',
    'Status: Proposed',
    '',
    '## Context',
    '',
    esc.block(decision.context),
    '',
    '## Decision',
    '',
    esc.block(decision.decision),
    '',
    '## Consequences',
    '',
    esc.block(decision.consequences === '' ? 'Not stated.' : decision.consequences),
    '',
    `Source cards: ${sourceLinks(decision.sources, 1)}`,
    '',
  ].join('\n');
}

// RF-601, RF-602
export function entityMappingMarkdown(handoff: HandoffPackage, esc: MarkdownEscaper): string {
  const rows = handoff.content.entities.map(
    (entity) =>
      `| ${esc.inline(entity.legacy)} | ${esc.inline(entity.target)} | ${esc.inline(entity.notes)} | ${sourceLinks(entity.sources)} |`,
  );
  return [
    '# Entity mapping',
    '',
    'How each legacy entity maps to an entity of the new system.',
    '',
    ...(rows.length === 0
      ? ['The planner mapped no entity.']
      : ['| Legacy entity | Target entity | Notes | Source cards |', '|---|---|---|---|', ...rows]),
    '',
  ].join('\n');
}

// RF-601
export function roadmapMarkdown(handoff: HandoffPackage, esc: MarkdownEscaper): string {
  const { phases, tasks } = handoff.content;
  return [
    '# Roadmap',
    '',
    'The phases of the move, in order, each with its exit criteria.',
    '',
    ...phases.flatMap((phase) => {
      const own = tasks.filter((task) => task.phase === phase.number);
      return [
        `## Phase ${String(phase.number)}`,
        '',
        `**${esc.inline(phase.name)}**: ${esc.inline(phase.goal)}`,
        '',
        'Exit criteria:',
        '',
        ...bullets(phase.exitCriteria, esc, 'None stated.'),
        '',
        `Task cards: ${own.length === 0 ? 'none' : own.map((task) => idLink(task.id, handoffFiles.tasks)).join(', ')}`,
        '',
      ];
    }),
  ].join('\n');
}

// RF-601
export function tasksMarkdown(handoff: HandoffPackage, esc: MarkdownEscaper): string {
  const { tasks, phases } = handoff.content;
  return [
    '# Task cards',
    '',
    'Work a developer can pick up, each in one phase of the roadmap with its acceptance criteria.',
    '',
    ...tasks.flatMap((task) => [
      `## ${task.id}`,
      '',
      `**${esc.inline(task.title)}**`,
      '',
      `Phase: ${phaseLink(phases[task.phase - 1], task.phase, esc)}`,
      '',
      `Requirements: ${task.requirements.length === 0 ? 'none' : task.requirements.map((id) => idLink(id, handoffFiles.requirements)).join(', ')}`,
      '',
      'Acceptance criteria:',
      '',
      ...bullets(task.acceptanceCriteria, esc, 'None stated.'),
      '',
    ]),
  ].join('\n');
}
