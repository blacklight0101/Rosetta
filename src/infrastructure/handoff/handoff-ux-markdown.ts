import type { HandoffPackage } from '../../application/plan/handoff-package.js';
import { targetScreenMap } from '../../domain/diagrams/target-screen-map.js';
import { byCodeUnit } from '../../domain/code-map/code-unit-order.js';
import { MAX_SCREENS, type TargetScreen } from '../../domain/planning/target-ux.js';
import { fenced } from '../cards/flow-diagram-section.js';
import type { MarkdownEscaper } from '../cards/markdown-text.js';
import type { TextMasker } from '../guards/secret-masker.js';
import { handoffFiles, idLink } from './handoff-links.js';
import { wireframeHtml } from './handoff-wireframe-html.js';

// RF-626, RF-620, RF-602, RF-507, ADR-013, Q-27: `ux/` of the hand-off package: an index with the
// target screen map (a Mermaid diagram generated by code) and every legacy screen card kept,
// merged or dropped with its reason and its screen; one plain HTML wireframe per main screen,
// drawn by code from the legacy cards (handoff-wireframe-html.ts); and the design brief for an
// external design tool (audience, tone, components needed, accessibility target). The package holds
// no visual design. Files are named by card ids the code checked, never by model text; every piece
// of model text is escaped inline text, masked first by the escaper.

const WIREFRAMES = 'wireframes';
const PLACEHOLDER =
  'Not stated: the cards do not say this. Confirm it with the product owner before the design starts.';

/** `ux/wireframes/SCRN-001.html`. */
function wireframeFile(id: string): string {
  return `ux/${WIREFRAMES}/${id}.html`;
}

const sourcesLink = (id: string): string => idLink(id, handoffFiles.sources, 1);
const pageLink = (id: string): string => `${WIREFRAMES}/${id}.html`;

function targetCell(handoff: HandoffPackage, target: string | null, esc: MarkdownEscaper): string {
  const screen = handoff.ux.screens.find((each) => each.id === target);
  return screen === undefined ? 'none' : `[${esc.inline(screen.name)}](${pageLink(screen.id)})`;
}

function legacyTable(handoff: HandoffPackage, esc: MarkdownEscaper): string[] {
  return [
    '| Legacy screen card | Screen | Decision | Target screen | Why |',
    '|---|---|---|---|---|',
    ...handoff.ux.legacy.map((each) => {
      const screen = esc.inline(each.route === '' ? each.title : each.route);
      const target = targetCell(handoff, each.target, esc);
      return `| ${sourcesLink(each.cardId)} | ${screen} | ${each.disposition} | ${target} | ${esc.inline(each.reason)} |`;
    }),
  ];
}

function replaces(screen: TargetScreen): string {
  return screen.cards.map(sourcesLink).join(', ');
}

// RF-626, RF-620
function indexMarkdown(handoff: HandoffPackage, esc: MarkdownEscaper, masker: TextMasker): string {
  const { ux } = handoff;
  if (ux.legacy.length === 0) {
    return [
      '# User-interface material',
      '',
      'No verified screen card exists, so there is no screen to plan, no wireframe and no design brief. The package holds no visual design.',
      '',
    ].join('\n');
  }
  const intro = [
    '# User-interface material',
    '',
    `The screens of the new system planned from the verified legacy screen cards ([source cards](../${handoffFiles.sources})): each legacy screen is kept, merged into another screen or dropped, with the reason. The package holds no visual design: the wireframes are plain HTML pages of layout boxes (fields, actions and navigation only) and the design itself comes from the team's design tool using the [design brief](design-brief.md). At most ${String(MAX_SCREENS)} screens get a wireframe (Q-27); the others are dropped with that reason.`,
    '',
  ];
  return [
    ...intro,
    '## Target screen map',
    '',
    ...fenced(targetScreenMap(ux, (text) => masker.mask(text).text)),
    '## Legacy screens',
    '',
    ...legacyTable(handoff, esc),
    '',
    '## Wireframes',
    '',
    ...(ux.screens.length === 0
      ? ['No screen is kept: every legacy screen is dropped.']
      : ux.screens.map(
          (screen) =>
            `- [${pageLink(screen.id)}](${pageLink(screen.id)}): ${esc.inline(screen.name)} (replaces ${replaces(screen)})`,
        )),
    '',
  ].join('\n');
}

function textOrPlaceholder(text: string, esc: MarkdownEscaper): string {
  return text === '' ? PLACEHOLDER : esc.inline(text);
}

function rolesLine(handoff: HandoffPackage, esc: MarkdownEscaper): string {
  const roles = [...new Set(handoff.ux.screens.flatMap((screen) => screen.roles))].toSorted(
    byCodeUnit,
  );
  return roles.length === 0
    ? 'The legacy screens name no role.'
    : `Roles named by the legacy screens: ${roles.map((role) => esc.inline(role)).join(', ')}.`;
}

function frontEndLine(handoff: HandoffPackage, esc: MarkdownEscaper): string {
  const choice = handoff.brief.stack.find((entry) => entry.layer === 'front-end')?.choice;
  return choice === undefined
    ? 'Front end: not chosen in the planning brief.'
    : `Front end: ${esc.inline(choice)} (from the planning brief).`;
}

// RF-626
function designBriefMarkdown(handoff: HandoffPackage, esc: MarkdownEscaper): string {
  const { designBrief, screens } = handoff.ux;
  return [
    '# Design brief for an external design tool',
    '',
    `This brief is the input for the team's design tool. Rosetta generates no visual design: the [wireframes](README.md) show layout, fields, actions and navigation only, and colours, type and imagery come from the design tool.`,
    '',
    '## Audience',
    '',
    textOrPlaceholder(designBrief.audience, esc),
    '',
    rolesLine(handoff, esc),
    '',
    '## Tone',
    '',
    textOrPlaceholder(designBrief.tone, esc),
    '',
    '## Front end',
    '',
    frontEndLine(handoff, esc),
    '',
    '## Components needed',
    '',
    ...(designBrief.components.length === 0
      ? [PLACEHOLDER]
      : designBrief.components.map((component) => `- ${esc.inline(component)}`)),
    '',
    '## Screens to design',
    '',
    ...(screens.length === 0
      ? ['No screen is kept, so there is nothing to design yet.']
      : screens.map((screen) => {
          const purpose = screen.purpose === '' ? '' : `${esc.inline(screen.purpose)} `;
          return `- [${esc.inline(screen.name)}](${pageLink(screen.id)}): ${purpose}Replaces ${replaces(screen)}.`;
        })),
    '',
    '## Accessibility target',
    '',
    'The interface meets WCAG 2.1 AA: enough colour contrast, every function usable with a keyboard, a logical heading structure, a label for every field, and status never shown by colour alone.',
    '',
  ].join('\n');
}

/** The files of `ux/` by their path inside the package. */
// RF-626, RF-620
export function uxFiles(
  handoff: HandoffPackage,
  esc: MarkdownEscaper,
  masker: TextMasker,
): Record<string, string> {
  const { ux } = handoff;
  const mask = (text: string): string => masker.mask(text).text;
  const wireframes = ux.screens.map((screen): [string, string] => [
    wireframeFile(screen.id),
    wireframeHtml(screen, mask),
  ]);
  return {
    [handoffFiles.ux]: indexMarkdown(handoff, esc, masker),
    ...(ux.legacy.length === 0
      ? {}
      : { [handoffFiles.designBrief]: designBriefMarkdown(handoff, esc) }),
    ...Object.fromEntries(wireframes),
  };
}
