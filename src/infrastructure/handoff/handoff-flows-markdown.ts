import type { HandoffPackage } from '../../application/plan/handoff-package.js';
import { targetFlowDiagram } from '../../domain/diagrams/target-flow-diagram.js';
import { MAX_FLOWS, type FlowStep, type MappedFlow } from '../../domain/planning/target-flows.js';
import { fenced } from '../cards/flow-diagram-section.js';
import type { MarkdownEscaper } from '../cards/markdown-text.js';
import type { TextMasker } from '../guards/secret-masker.js';
import { handoffFiles, idLink } from './handoff-links.js';

// RF-625, RF-602, RF-603, ADR-013, Q-27: `flows/` of the hand-off package: an index of the main
// journeys (each linking its file and its legacy `FLOW` card) with the journeys out of scope and
// why, and one file per main journey with its steps mapped to target components and a Mermaid
// sequence diagram generated by code. A file is named by the card id, which the code checked, never
// by model text. The only code block is the diagram; every other piece of model text is escaped
// inline text, masked first by the escaper.

/** The folder of the flow files inside the package. */
const FOLDER = 'flows';

/** `flows/FLOW-001.md`. */
// RF-625
export function flowFile(cardId: string): string {
  return `${FOLDER}/${cardId}.md`;
}

const sourcesLink = (id: string): string => idLink(id, handoffFiles.sources, 1);

// RF-625, Q-27
export function flowsIndexMarkdown(handoff: HandoffPackage, esc: MarkdownEscaper): string {
  const { flows, outOfScope } = handoff.flows;
  return [
    '# Target flows',
    '',
    `Each main journey of the legacy system drawn over the [target architecture](../${handoffFiles.architecture}): its steps are mapped to the components that will perform them, and each file links the legacy flow card it comes from. At most ${String(MAX_FLOWS)} journeys get a file (Q-27); the others are listed below with their legacy cards.`,
    '',
    '## Main journeys',
    '',
    ...(flows.length === 0
      ? ['No journey is mapped.']
      : flows.map(
          (flow) =>
            `- [${flow.cardId}](${flow.cardId}.md): ${esc.inline(flow.title)} (legacy flow card ${sourcesLink(flow.cardId)})`,
        )),
    '',
    '## Out of scope',
    '',
    ...(outOfScope.length === 0
      ? ['No journey is out of scope.']
      : [
          '| Legacy flow card | Journey | Why it has no flow |',
          '|---|---|---|',
          ...outOfScope.map(
            (flow) =>
              `| ${sourcesLink(flow.cardId)} | ${esc.inline(flow.title)} | ${esc.inline(flow.reason)} |`,
          ),
        ]),
    '',
  ].join('\n');
}

function stepRow(step: FlowStep, index: number, esc: MarkdownEscaper): string {
  const touches = step.touches === null ? 'none' : sourcesLink(step.touches);
  const component = step.component === null ? 'not mapped' : esc.inline(step.component);
  const action = step.action === '' ? '' : esc.inline(step.action);
  return `| ${String(index + 1)} | ${esc.inline(`${step.claimId}: ${step.text}`)} | ${touches} | ${component} | ${action} |`;
}

// RF-625, RF-602
export function flowMarkdown(
  flow: MappedFlow,
  handoff: HandoffPackage,
  esc: MarkdownEscaper,
  masker: TextMasker,
): string {
  const left = handoff.excluded.filter((claim) => claim.cardId === flow.cardId);
  return [
    `# ${flow.cardId} ${esc.inline(flow.title)}`,
    '',
    `Legacy flow card: ${sourcesLink(flow.cardId)}`,
    '',
    `Trigger: ${flow.trigger === '' ? 'not stated' : esc.inline(flow.trigger)}`,
    '',
    `Outcome: ${flow.outcome === '' ? 'not stated' : esc.inline(flow.outcome)}`,
    '',
    '## Sequence diagram',
    '',
    ...fenced(targetFlowDiagram(flow, (text) => masker.mask(text).text)),
    '## Steps',
    '',
    '| Step | Legacy step | Touches | Target component | What it does |',
    '|---|---|---|---|---|',
    ...flow.steps.map((step, index) => stepRow(step, index, esc)),
    '',
    ...(left.length === 0
      ? []
      : [
          `Steps of the legacy card the verifier did not support and so left out: ${left.map((claim) => esc.inline(claim.claimId)).join(', ')}.`,
          '',
        ]),
  ].join('\n');
}
