import { targetModelDiagram } from '../../domain/diagrams/target-model-diagram.js';
import type {
  DroppedField,
  ForeignKey,
  LegacySource,
  ModelColumn,
  ModelTable,
  TargetDataModel,
} from '../../domain/planning/data-model.js';
import { fenced } from '../cards/flow-diagram-section.js';
import type { FormulaRow } from '../../domain/planning/workbook-formulas.js';
import type { MarkdownEscaper } from '../cards/markdown-text.js';
import type { TextMasker } from '../guards/secret-masker.js';
import { calculatedMark } from './handoff-formulas-markdown.js';
import { handoffFiles, idLink } from './handoff-links.js';

// RF-623, RF-603, RF-602, ADR-013: `data-model.md` of the hand-off package, the target data model
// table by table. Each column names the legacy card, claim and field it comes from, or "new"; the
// legacy fields with no target column are listed as dropped with the reason; a type change that
// can lose data is a migration risk. The only code block is the Mermaid diagram generated by code:
// the file holds no executable DDL (names and types are checked by the domain, everything else is
// escaped inline text). Model text goes through the escaper, which masks it first.

/** P3-94: the formula rows of the calculated table column a legacy source names; none without workbook formulas. */
type CalculatedBy = (legacy: LegacySource) => readonly FormulaRow[];

function legacyText(
  legacy: LegacySource | null,
  esc: MarkdownEscaper,
  calculated: CalculatedBy,
): string {
  if (legacy === null) return 'new';
  const link = idLink(legacy.cardId, handoffFiles.sources);
  return `${link} ${esc.inline(`${legacy.claimId}: ${legacy.field}`)}${calculatedMark(calculated(legacy))}`;
}

function columnRow(column: ModelColumn, esc: MarkdownEscaper, calculated: CalculatedBy): string {
  const nullable = column.nullable ? 'yes' : 'no';
  return `| ${esc.inline(column.name)} | ${esc.inline(column.type)} | ${nullable} | ${legacyText(column.legacy, esc, calculated)} |`;
}

function list(columns: readonly string[], esc: MarkdownEscaper): string {
  return esc.inline(columns.join(', '));
}

function foreignKeyLine(key: ForeignKey, esc: MarkdownEscaper): string {
  return `- Foreign key: ${list(key.columns, esc)} references ${esc.inline(key.references)} (${list(key.referencedColumns, esc)})`;
}

function constraintLines(table: ModelTable, esc: MarkdownEscaper): string[] {
  const lines = [
    ...(table.primaryKey.length === 0 ? [] : [`- Primary key: ${list(table.primaryKey, esc)}`]),
    ...table.uniqueKeys.map((key) => `- Unique: ${list(key, esc)}`),
    ...table.foreignKeys.map((key) => foreignKeyLine(key, esc)),
    ...table.checks.map((check) => `- Check: ${esc.inline(check)}`),
  ];
  return lines.length === 0 ? ['- None stated.'] : lines;
}

function indexLines(table: ModelTable, esc: MarkdownEscaper): string[] {
  if (table.indexes.length === 0) return ['- None stated.'];
  return table.indexes.map((index) => {
    const unique = index.unique ? ' (unique)' : '';
    const reason = index.reason === '' ? '' : `: ${esc.inline(index.reason)}`;
    return `- Index on ${list(index.columns, esc)}${unique}${reason}`;
  });
}

function tableSection(table: ModelTable, esc: MarkdownEscaper, calculated: CalculatedBy): string[] {
  const built =
    table.sources.length === 0
      ? 'Built from: no legacy entity (a new table)'
      : `Built from: ${table.sources.map((id) => idLink(id, handoffFiles.sources)).join(', ')}`;
  return [
    `### ${esc.inline(table.name)}`,
    '',
    esc.inline(table.purpose),
    '',
    built,
    '',
    '| Column | Type | Nullable | Legacy source |',
    '|---|---|---|---|',
    ...table.columns.map((column) => columnRow(column, esc, calculated)),
    '',
    'Keys and constraints:',
    '',
    ...constraintLines(table, esc),
    '',
    'Indexes:',
    '',
    ...indexLines(table, esc),
    '',
  ];
}

function droppedRow(field: DroppedField, esc: MarkdownEscaper): string {
  const name = field.field === '' ? 'not named' : esc.inline(field.field);
  const card = idLink(field.cardId, handoffFiles.sources);
  return `| ${name} | ${esc.inline(field.claimId)} | ${card} | ${esc.inline(field.reason)} |`;
}

function droppedSection(model: TargetDataModel, esc: MarkdownEscaper): string[] {
  return [
    '## Dropped legacy fields',
    '',
    ...(model.dropped.length === 0
      ? ['Every legacy field the cards state has a target column.']
      : [
          '| Legacy field | Claim | Card | Reason |',
          '|---|---|---|---|',
          ...model.dropped.map((field) => droppedRow(field, esc)),
        ]),
    '',
  ];
}

function riskSection(model: TargetDataModel, esc: MarkdownEscaper): string[] {
  const risks = model.tables.flatMap((table) =>
    table.columns
      .filter((column) => column.migrationRisk !== '')
      .map((column) => {
        const where = esc.inline(`${table.name}.${column.name}`);
        const { legacy } = column;
        const card = legacy === null ? '' : idLink(legacy.cardId, handoffFiles.sources);
        const source = legacy === null ? '' : ` (${card} ${esc.inline(legacy.claimId)})`;
        return `- ${where}${source}: ${esc.inline(column.migrationRisk)}`;
      }),
  );
  return [
    '## Migration risks',
    '',
    ...(risks.length === 0 ? ['No type change that can lose data was named.'] : risks),
    '',
  ];
}

function databaseLine(database: string | null, esc: MarkdownEscaper): string {
  return database === null
    ? 'Database: not chosen in the planning brief; the types below are general type names, to confirm.'
    : `Database: **${esc.inline(database)}**.`;
}

function noTableText(model: TargetDataModel): string {
  return model.dropped.length === 0
    ? 'The verified cards show no legacy entity, so no table was derived from them.'
    : 'The planner wrote no usable table. Every legacy field the cards state is listed below, to be confirmed.';
}

// RF-623, RF-603
export function dataModelMarkdown(
  model: TargetDataModel,
  esc: MarkdownEscaper,
  masker: TextMasker,
  calculated: CalculatedBy = () => [],
): string {
  const diagram =
    model.tables.length === 0 ? [] : fenced(targetModelDiagram(model, (t) => masker.mask(t).text));
  return [
    '# Target data model',
    '',
    databaseLine(model.database, esc),
    '',
    `The tables of the new system. Each column names the legacy field it comes from, or "new". This file holds no executable DDL: the first task card of the implementation plan writes the migrations in the chosen stack. How each legacy entity maps to a target entity is in [the entity mapping](${handoffFiles.entities}).`,
    '',
    ...(model.tables.length === 0
      ? [noTableText(model), '']
      : ['## Entity-relationship diagram', '', ...diagram, '## Tables', '']),
    ...model.tables.flatMap((table) => tableSection(table, esc, calculated)),
    ...droppedSection(model, esc),
    ...riskSection(model, esc),
  ].join('\n');
}
