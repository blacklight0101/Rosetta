// RF-622, RF-608, RF-609, RF-610, ADR-018, DEC-134: the technical requirements document. Seven
// sections, each opening with the decision records that decided it (a link to each) or with the
// reason none applies, so no technical choice stands without its record. The component diagram is
// generated by code from the planner's components; the integrations come from the `INT` cards of
// the analysis and link to them. Plain Markdown; model, repository and user text goes through the
// escaper (and the masker for the diagram), so it shows as text and adds no link, heading or HTML.

/** The line that opens a section: the records that decided it, or why there are none. */
function decisionsLine(ids: readonly string[], none: string): string {
  const linked = [...new Set(ids.filter((id) => id !== ''))];
  if (linked.length === 0) return `Decision records: none apply. ${none}`;
  return `Decision records: ${linked.map(decisionLink).join(', ')}`;
}

function overview(handoff: HandoffPackage, esc: MarkdownEscaper, masker: TextMasker): string[] {
  const { content, style, choices } = handoff;
  const names = content.components.map((component) => ({
    name: masker.mask(component.name).text,
    dependsOn: component.dependsOn.map((name) => masker.mask(name).text),
  }));
  return [
    '## Architecture overview',
    '',
    decisionsLine(
      [choices.style],
      'The chosen style is not in the catalogue, so no record was written.',
    ),
    '',
    `Architecture style: ${esc.inline(style.title)}. ${esc.inline(style.rule)}`,
    '',
    ...(content.summary === '' ? [] : [esc.block(content.summary), '']),
    ...(names.length === 0
      ? ['The planner named no component.', '']
      : fenced(componentDiagram(names))),
    `Each component and what it is responsible for: [target architecture](${handoffFiles.architecture}).`,
    '',
  ];
}

function stackSection(handoff: HandoffPackage, esc: MarkdownEscaper): string[] {
  const { stack } = handoff.choices;
  const chosen = new Set(stack.map((entry) => entry.layer));
  const open = stackLayers.filter((layer) => !chosen.has(layer)).map((layer) => layerNames[layer]);
  return [
    '## Stack per layer',
    '',
    decisionsLine(
      stack.map((entry) => entry.decision),
      'The owner chose no technology for any layer.',
    ),
    '',
    ...(stack.length === 0
      ? []
      : [
          '| Layer | Technology | Decision record |',
          '|---|---|---|',
          ...stack.map(
            (entry) =>
              `| ${esc.inline(entry.name)} | ${esc.inline(entry.choice)}${entry.proposed === true ? ' (proposed by Rosetta)' : ''} | ${entry.decision === '' ? 'none' : decisionLink(entry.decision)} |`,
          ),
          '',
        ]),
    ...proposalLines(handoff, esc),
    ...(open.length === 0
      ? []
      : [
          `Not chosen: ${open.join(', ')}. The package names no technology for these layers; the open questions list them.`,
          '',
        ]),
  ];
}

const actionNames = { keep: 'Keep', replace: 'Replace' } as const;

function integrationRow(
  card: HandoffPackage['sources'][number],
  planned: PlanIntegration | undefined,
  esc: MarkdownEscaper,
): string {
  const action = planned === undefined ? 'Not decided' : actionNames[planned.action];
  const note =
    planned === undefined
      ? 'Decide before the build whether to keep or replace it.'
      : esc.inline(planned.note);
  return `| ${idLink(card.id, handoffFiles.sources)} | ${esc.inline(card.title)} | ${action} | ${note} |`;
}

function integrationsSection(handoff: HandoffPackage, esc: MarkdownEscaper): string[] {
  const { integrations } = handoff.content.technical;
  const cards = handoff.sources.filter((card) => card.type === 'INT');
  const staying = handoff.brief.context.keepIntegrations;
  return [
    '## Integrations',
    '',
    decisionsLine(
      integrations.map((each) => each.decision),
      'The planner recorded no decision about the integrations.',
    ),
    '',
    ...(cards.length === 0
      ? ['The cards show no integration.', '']
      : [
          '| Card | Integration | Action | Note |',
          '|---|---|---|---|',
          ...cards.map((card) =>
            integrationRow(
              card,
              integrations.find((each) => each.card === card.id),
              esc,
            ),
          ),
          '',
        ]),
    ...(staying.length === 0
      ? []
      : [
          `Integrations that must stay as they are, as the owner stated: ${staying.map((each) => esc.inline(each)).join(', ')}.`,
          '',
        ]),
  ];
}

function securitySection(handoff: HandoffPackage, esc: MarkdownEscaper): string[] {
  const { security } = handoff.content.technical;
  return [
    '## Security and data protection',
    '',
    decisionsLine(
      security.map((each) => each.decision),
      'The planner recorded no decision about security.',
    ),
    '',
    ...securityLines(handoff, esc),
  ];
}

function targetsSection(handoff: HandoffPackage, esc: MarkdownEscaper): string[] {
  const { targets } = handoff.content.technical;
  return [
    '## Non-functional targets',
    '',
    decisionsLine(
      targets.map((each) => each.decision),
      'The planner recorded no decision about the targets.',
    ),
    '',
    ...(targets.length === 0
      ? [
          'The cards and the answers name no non-functional target. Set the targets with the owner before the build.',
          '',
        ]
      : [
          '| Target | Value | Source cards |',
          '|---|---|---|',
          ...targets.map(
            (each) =>
              `| ${esc.inline(each.name)} | ${esc.inline(each.target)} | ${sourceLinks(each.sources)} |`,
          ),
          '',
        ]),
  ];
}

function deploymentSection(handoff: HandoffPackage, esc: MarkdownEscaper): string[] {
  const { environments } = handoff.content.technical;
  const hosting = handoff.choices.stack.find((entry) => entry.layer === 'hosting');
  return [
    '## Deployment and environments',
    '',
    decisionsLine(
      [hosting?.decision ?? '', ...environments.map((each) => each.decision)],
      'The owner chose no hosting and the planner recorded no decision about the environments.',
    ),
    '',
    hosting === undefined
      ? 'Hosting: none chosen; the package names no hosting technology.'
      : `Hosting: ${esc.inline(hosting.choice)} (${decisionLink(hosting.decision)})`,
    '',
    ...(environments.length === 0
      ? ['The cards and the answers name no environment.', '']
      : [
          '| Environment | Purpose |',
          '|---|---|',
          ...environments.map(
            (each) => `| ${esc.inline(each.name)} | ${esc.inline(each.purpose)} |`,
          ),
          '',
        ]),
  ];
}

function migrationSection(handoff: HandoffPackage, esc: MarkdownEscaper): string[] {
  const { brief, choices, content } = handoff;
  const info = migrationStrategyInfo[brief.migration];
  const record = choices.migration === '' ? '' : ` (${decisionLink(choices.migration)})`;
  const data = brief.context.dataMigration;
  return [
    '## Migration approach',
    '',
    decisionsLine([choices.migration], 'No record was written for the strategy.'),
    '',
    `Strategy: ${esc.inline(info.title)}${record}`,
    '',
    ...strategyLines(handoff, esc),
    esc.inline(info.ordering),
    '',
    `Data migration: ${data === null ? 'not stated' : esc.inline(data)}`,
    '',
    ...(content.phases.length === 0
      ? ['The planner named no phase.', '']
      : [
          ...content.phases.map(
            (phase) =>
              `- [Phase ${String(phase.number)}](${handoffFiles.roadmap}#phase-${String(phase.number)}): ${esc.inline(phase.name)}`,
          ),
          '',
        ]),
  ];
}

// RF-622
export function trdMarkdown(
  handoff: HandoffPackage,
  esc: MarkdownEscaper,
  masker: TextMasker,
): string {
  return [
    '# Technical requirements document',
    '',
    'The technical choices for the new system in one place. Each section opens with the decision records that decided it, or says why none applies.',
    '',
    ...overview(handoff, esc, masker),
    ...stackSection(handoff, esc),
    ...integrationsSection(handoff, esc),
    ...securitySection(handoff, esc),
    ...targetsSection(handoff, esc),
    ...deploymentSection(handoff, esc),
    ...migrationSection(handoff, esc),
  ].join('\n');
}
