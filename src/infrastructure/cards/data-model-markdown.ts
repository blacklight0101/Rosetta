import type { Card } from '../../domain/cards/card.js';
import { entityDiagram, type EntityModel } from '../../domain/diagrams/entity-diagram.js';
import { entityModelOf } from '../../domain/diagrams/entity-model.js';
import type { TextMasker } from '../guards/secret-masker.js';
import { cardPath } from './card-markdown.js';
import { citationLink, type PermalinkSource } from './citation-link.js';
import { maskCardText } from './mask-card-text.js';
import { markdownEscaper, type MarkdownEscaper } from './markdown-text.js';

// RF-262, RF-204, DEC-134: `data-model.md`, the legacy data model from the ENT cards. Each entity
// appears once, in card id order, with its claims (the fields, keys and relations the card states),
// every claim with the citations it came from and its status, rejected ones included. The ER
// diagram is generated by `entityDiagram`; the model never writes Mermaid. A relation whose
// cardinality the cards do not state is drawn as unknown and listed under "To confirm".

function claimLines(card: Card, source: PermalinkSource, esc: MarkdownEscaper): string[] {
  return card.claims.map((claim) => {
    const evidence = claim.citations.map((citation) => citationLink(citation, source)).join(', ');
    const cited = evidence === '' ? '' : ` (${evidence})`;
    return `- ${claim.claimId} [${claim.status}] ${esc.inline(claim.text)}${cited}`;
  });
}

function entitySection(card: Card, source: PermalinkSource, esc: MarkdownEscaper): string[] {
  const merged = card.mergedFrom ?? [];
  return [
    `### ${card.id} ${esc.inline(card.title)} ([card file](${cardPath(card)}))`,
    '',
    esc.block(card.summary),
    '',
    `Area: ${esc.inline(card.area)} | Confidence: ${card.confidence}`,
    '',
    ...(merged.length === 0 ? [] : [`Merged from: ${esc.inline(merged.join(', '))}`, '']),
    ...(card.note === undefined ? [] : [`Note: ${esc.inline(card.note)}`, '']),
    'Fields, keys and relations as the card states them:',
    '',
    ...claimLines(card, source, esc),
    '',
  ];
}

function toConfirm(model: EntityModel, esc: MarkdownEscaper): string[] {
  const none =
    '- The entity cards record no relations between entities, so none is drawn. Confirm which entities are related and how many of each take part.';
  if (model.relations.length === 0) return [none];
  const name = (id: string): string =>
    esc.inline(`${id} ${model.entities.find((entity) => entity.cardId === id)?.name ?? ''}`);
  const unknown = model.relations.filter(
    (relation) => relation.fromCardinality === 'unknown' || relation.toCardinality === 'unknown',
  );
  if (unknown.length === 0) return ['- Nothing is left to confirm.'];
  return unknown.map(
    (relation) =>
      `- ${name(relation.from)} and ${name(relation.to)} (${esc.inline(relation.label)}): cardinality unknown`,
  );
}

// RF-262
export function renderDataModel(
  cards: readonly Card[],
  source: PermalinkSource,
  masker: TextMasker,
  model?: EntityModel,
): string {
  const masked = maskCardText(cards, masker);
  const entities = entityModelOf(masked);
  const drawn = model ?? entities;
  const esc = markdownEscaper(masker);
  const byId = new Map<string, Card>();
  for (const card of masked) if (!byId.has(card.id)) byId.set(card.id, card);
  const lines = [
    '# Legacy data model',
    '',
    'The entities of the legacy application as its entity cards state them. Each line cites the code it came from.',
    '',
    '## Entity diagram',
    '',
    '```mermaid',
    entityDiagram(drawn).trimEnd(),
    '```',
    '',
    '## Entities',
    '',
    ...entities.entities.flatMap((entity) => {
      const card = byId.get(entity.cardId);
      return card === undefined ? [] : entitySection(card, source, esc);
    }),
    '## To confirm',
    '',
    ...toConfirm(drawn, esc),
  ];
  return `${masker.mask(lines.join('\n')).text.trimEnd()}\n`;
}
