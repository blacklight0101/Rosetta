const body = [...found.entries()]
  .sort(([left], [right]) => (left < right ? -1 : 1))
  .map(([key, points]) => {
    const list = points
      .sort((left, right) => left - right)
      .map((point) => `0x${point.toString(16)}`);
    return `  ${JSON.stringify(key)}: [${list.join(', ')}],`;
  })
  .join('\n');
process.stdout.write(
  `${header}\nexport const markerConfusables: Readonly<Record<string, readonly number[]>> = {\n${body}\n};\n`,
);
