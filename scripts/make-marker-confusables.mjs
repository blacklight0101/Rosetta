// RF-145: writes src/domain/egress/marker-confusables.ts from the Unicode confusables data
// (UTS #39): `node scripts/make-marker-confusables.mjs path/to/confusables.txt > file.ts`, then
// `npx prettier --write` on the file. Only the characters that stand for a letter of the marker
// name (R O S E T A D N) or for `<`, `>` and `-` are kept, so the table stays small.
import { readFile } from 'node:fs/promises';

const [file] = process.argv.slice(2);
if (file === undefined) throw new Error('usage: make-marker-confusables.mjs <confusables.txt>');

const text = await readFile(file, 'utf8');
const version = /^# Version: (.+)$/m.exec(text)?.[1] ?? 'unknown';
const date = /^# Date: (.+)$/m.exec(text)?.[1] ?? 'unknown';
const wanted = new Set([...'ROSETADN<>-']);
const found = new Map();
for (const line of text.split('\n')) {
  const match = /^([0-9A-F ]+);\s*([0-9A-F ]+);/.exec(line);
  if (match === null) continue;
  const [source, target] = [match[1], match[2]].map((part) =>
    String.fromCodePoint(
      ...part
        .trim()
        .split(/\s+/)
        .map((hex) => Number.parseInt(hex, 16)),
    ),
  );
  const key = target.toUpperCase();
  if (source.length === 0 || [...source].length !== 1 || source.codePointAt(0) < 0x80) continue;
  if ([...key].length !== 1 || !wanted.has(key)) continue;
  found.set(key, [...(found.get(key) ?? []), source.codePointAt(0)]);
}

const header = `// RF-145: GENERATED by scripts/make-marker-confusables.mjs from the Unicode confusables data
// (confusables.txt, UTS #39, version ${version}, ${date}). Do not edit by hand.
// © Unicode, Inc. Used under the Unicode License v3 (https://www.unicode.org/license.txt).
//
// The non-ASCII characters the data lists as confusable with a letter of the marker name
// (ROSETTA-DATA, END) or with \`<\`, \`>\` and \`-\`, by the ASCII character they imitate (letters
// upper case). It is one input to the marker check, never the only one: marker-fold.ts and
// marker-keyword.ts hold what this table does not.
`;
const body = [...found.entries()]
  .sort(([left], [right]) => (left < right ? -1 : 1))
  .map(([key, points]) => {
    const list = points
      .sort((left, right) => left - right)
      .map((point) => `0x${point.toString(16)}`);
    return `  ${JSON.stringify(key)}: [${list.join(', ')}],`;
  })
  .join('\n');
process.stdout.write(
  `${header}\nexport const markerConfusables: Readonly<Record<string, readonly number[]>> = {\n${body}\n};\n`,
);
