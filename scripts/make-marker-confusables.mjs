// The non-ASCII characters the data lists as confusable with a letter of the marker name
// (ROSETTA-DATA, END) or with \`<\`, \`>\` and \`-\`, by the ASCII character they imitate (letters
// upper case). It is one input to the marker check, never the only one: marker-fold.ts and
// marker-skeleton.ts hold what this table does not.
